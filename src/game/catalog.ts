export function getAllAvailableBuildings(mods: ModPackage[]): BuildingDefinition[] {
  const activeModBuildings = mods
    .filter((m) => m.enabled)
    .map((m) => m.building)
    .filter((b) => !(b.customLotData && b.isZone)); // Hide custom RCI lots from manual build toolbar so they spawn organically in zones
  return [...BUILTIN_BUILDINGS, ...activeModBuildings];
}
